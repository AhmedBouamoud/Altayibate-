function renderLine(line: string, i: number) {
  if (line.startsWith("## ")) {
    return <h2 key={i} className="text-2xl font-bold text-gray-900 mt-8 mb-4">{line.slice(3)}</h2>;
  }
  if (line.startsWith("> ")) {
    return (
      <blockquote key={i} className="border-r-4 border-amber-400 bg-amber-50 px-5 py-4 my-6 rounded-lg text-amber-800 text-sm leading-relaxed">
        {line.slice(2)}
      </blockquote>
    );
  }
  if (line.startsWith("**") && line.includes(":**")) {
    const [bold, rest] = line.split(":**");
    return (
      <p key={i} className="text-gray-700 leading-loose mb-3">
        <strong className="text-gray-900">{bold.slice(2)}:</strong>{rest}
      </p>
    );
  }
  return <p key={i} className="text-gray-600 leading-loose mb-4">{line}</p>;
}

