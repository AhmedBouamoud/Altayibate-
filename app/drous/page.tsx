const subjects3AC = ["الكل", "التاريخ", "الجغرافيا", "التربية على المواطنة"];
const subjects1Bac = ["الكل", "التاريخ", "الجغرافيا"];

const subjectColors: Record<string, string> = {
  "التاريخ": "bg-amber-100 text-amber-800 border-amber-200",
  "الجغرافيا": "bg-emerald-100 text-emerald-800 border-emerald-200",
  "التربية على المواطنة": "bg-blue-100 text-blue-800 border-blue-200",
};

function LessonCard({ lesson }: { lesson: Lesson }) {
  const [expanded, setExpanded] = useState(false);
  const done = lesson.status === "مكتمل";

  return (
    <div className={`rounded-2xl border bg-white transition-all duration-200 overflow-hidden ${done ? "border-gray-200 hover:border-primary-200 hover:shadow-md" : "border-gray-100 opacity-60"}`}>
      <div className="p-5">
        <div className="flex items-start justify-between gap-3 mb-3">
          <div className="flex items-center gap-2 flex-wrap">
            <span className={`text-xs font-semibold px-2.5 py-1 rounded-full border ${subjectColors[lesson.subject] ?? "bg-gray-100 text-gray-700 border-gray-200"}`}>
              {lesson.subject}
            </span>
            <span className="text-xs text-gray-400">{lesson.semester}</span>
          </div>
          <span className={`flex-shrink-0 text-xs font-bold px-2.5 py-1 rounded-full ${done ? "bg-green-100 text-green-700" : "bg-gray-100 text-gray-400"}`}>
            {done ? "✓ مكتمل" : "قريباً"}
          </span>
        </div>
        <h3 className={`font-bold text-base leading-snug mb-2 ${done ? "text-gray-900" : "text-gray-400"}`}>
          {lesson.num}. {lesson.title}
        </h3>
        {done && lesson.summary && (
          <>
            <p className={`text-gray-500 text-sm leading-relaxed ${expanded ? "" : "line-clamp-2"}`}>
              {lesson.summary}
            </p>
            <button
              onClick={() => setExpanded(!expanded)}
              className="mt-2 text-primary-600 text-xs font-semibold hover:underline"
            >
              {expanded ? "إخفاء التفاصيل" : "عرض التفاصيل"}
            </button>
            {expanded && lesson.concepts && (
              <div className="mt-3 p-3 bg-gray-50 rounded-xl border border-gray-100">
                <p className="text-xs font-bold text-gray-700 mb-1">المفاهيم الأساسية:</p>
                <p className="text-xs text-gray-600 leading-relaxed">{lesson.concepts}</p>
              </div>
            )}
          </>
        )}
      </div>
    </div>
  );
}

